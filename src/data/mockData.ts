export function getLoaBand(amount: number): LoaBand {
  if (amount <= 30000) return 'Band 1 (RM 1 - 30,000)';
  if (amount <= 100000) return 'Band 2 (RM 31,000 - 100,000)';
  return 'Band 3 (Above RM 100,000)';
}

